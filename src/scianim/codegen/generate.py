"""Deterministic scene module from a storyboard of registered components (spec 10.4, ADR-003).

The generated code is a projection of the storyboard: each object call embeds the object's own
YAML dictionaries, one `begin_scene()` opens a Manim section per scene, `checkpoint()` marks
every snapshot at its requested time, and reveals, sweeps, camera orbits, axes fades, moves, fades and
equation transforms are tracks that begin at their start times and advance together through `run_until()`
segments split at every breakpoint.
Regenerate rather than edit by hand.
"""

from __future__ import annotations

import pprint
from pathlib import Path

from scianim.project import scene_class_name
from scianim_core import AnimationSpec, ResolvedStyle, Storyboard
from scianim_core.storyboard import (
    Emphasize,
    FadeAxes,
    FadeObject,
    MoveObject,
    OrbitCamera,
    Scene,
    SceneAction,
    SceneObject,
    TransformEquation,
)
from scianim_core.style import Motion

HEADER = '''"""Generated by `scianim codegen` from storyboard.yaml. Do not edit; regenerate.

Project: {project_id}
Scene class: {class_name}
Storyboard revision: {revision}
"""

from scianim_bridge import SnapshotScene, checkpoint
from scianim_bridge import components as C


class {class_name}(SnapshotScene):
    def construct(self) -> None:
'''


def _literal(value: object, indent: int) -> str:
    text = pprint.pformat(value, width=88, sort_dicts=False)
    pad = " " * indent
    return ("\n" + pad).join(text.splitlines())


def object_call(obj: SceneObject, indent: int) -> str:
    pad = " " * indent
    args = [f'"{obj.id}"']
    if obj.style_role is not None:
        args.append(f'style_role="{obj.style_role}"')
    if obj.data is not None:
        args.append(f"data={_literal(obj.data.model_dump(mode='json', exclude_defaults=True), indent + 4)}")
    if obj.equation is not None:
        args.append(f"equation={_literal(obj.equation.model_dump(mode='json', exclude_defaults=True), indent + 4)}")
    if obj.params:
        args.append(f"params={_literal(obj.params, indent + 4)}")
    joined = ",\n".join(f"{pad}    {a}" for a in args)
    return f"{pad}{obj.id} = C.{obj.kind}(\n{pad}    self,\n{joined},\n{pad})"


def action_call(action: SceneAction, indent: int) -> str:
    pad = " " * indent
    if isinstance(action, OrbitCamera):
        args = [
            f"to_theta_degrees={action.to_theta_degrees!r}",
            f"to_phi_degrees={action.to_phi_degrees!r}",
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_orbit({', '.join(args)})"
    if isinstance(action, FadeAxes):
        args = [
            action.target,
            f"visible={action.visible!r}",
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_fade_axes({', '.join(args)})"
    if isinstance(action, MoveObject):
        args = [
            action.target,
            f"to_anchor={action.to_anchor!r}",
            f"by={list(action.by) if action.by is not None else None!r}",
            f"to_point={list(action.to_point) if action.to_point is not None else None!r}",
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_move({', '.join(args)})"
    if isinstance(action, FadeObject):
        args = [
            action.target,
            f"ink={action.target_ink:g}",
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_fade_object({', '.join(args)})"
    if isinstance(action, Emphasize):
        args = [
            action.target,
            f"symbols={action.symbols!r}",
            f'cue="{action.cue}"',
            f"from_target={action.from_target or None}",
            f"from_symbols={action.from_symbols!r}",
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_emphasize({', '.join(args)})"
    if isinstance(action, TransformEquation):
        args = [
            action.target,
            f'to="{action.to}"',
            f"at_seconds={action.at_seconds:g}",
            f"duration_seconds={action.duration_seconds:g}",
            f'action_id="{action.id}"',
            f'match="{action.match}"',
            f"easing={action.easing!r}",
        ]
        return f"{pad}{action.id} = self.begin_transform({', '.join(args)})"
    args = [
        action.target,
        f'"{action.parameter}"',
        f"to={action.to!r}",
        f"at_seconds={action.at_seconds:g}",
        f"duration_seconds={action.duration_seconds:g}",
        f'action_id="{action.id}"',
        f"easing={action.easing!r}",
        f"emphasize=[{', '.join(action.emphasize)}]",
        f"show_value={action.show_value!r}",
        f"value_decimals={action.value_decimals}",
        f"value_label={action.value_label!r}",
        f"lead_in_seconds={action.lead_in_seconds:g}",
    ]
    return f"{pad}{action.id} = self.begin_vary({', '.join(args)})"


def scene_block(scene: Scene, motion: Motion, is_last: bool) -> list[str]:
    """One scene as a sequence of segments between breakpoints.

    Tracks (reveals, sweeps, orbits, axes fades, moves, fades, transforms) begin at their start times and advance together through each segment;
    checkpoints sit at breakpoints and capture the state before anything that starts at the same time.
    Objects without a reveal time appear together at the scene start. A scene that fades out starts its fade
    `motion.transition_seconds` before its end, and tracks still running then continue through the fade
    (`end_scene(..., carry=[...])`) instead of stopping at speed; the last scene keeps its objects, so its tracks
    run to the scene's end.
    """
    ind = " " * 8
    lines = [
        f"{ind}# --- scene '{scene.id}': {scene.start_seconds:g}s to {scene.end_seconds:g}s",
        f"{ind}# {scene.purpose}",
        f'{ind}self.begin_scene("{scene.id}", start_seconds={scene.start_seconds:g})',
    ]
    if scene.narration is not None:
        lines.append(f"{ind}self.narrate({scene.narration.text!r})")
    for obj in scene.objects:
        lines.append(object_call(obj, 8))
    fade_start = (
        scene.end_seconds if is_last else max(scene.end_seconds - motion.transition_seconds, scene.start_seconds)
    )
    tracks: list[tuple[float, float, str, object]] = []
    for obj in scene.objects:
        begins = scene.start_seconds if obj.reveal_at_seconds is None else obj.reveal_at_seconds
        tracks.append((begins, min(begins + motion.reveal_seconds, fade_start), "reveal", obj))
    carried: list[str] = []
    for action in scene.actions:
        tracks.append((action.at_seconds, min(action.end_seconds, fade_start), "action", action))
        if action.end_seconds > fade_start + 1e-9 and action.at_seconds < fade_start - 1e-9:
            carried.append(action.id)  # still moving when the fade begins: it finishes during the fade
    tracks = [t for t in tracks if t[1] > t[0] + 1e-9]
    times = {scene.start_seconds, fade_start}
    times.update(t[0] for t in tracks)
    times.update(t[1] for t in tracks)
    times.update(snap.at_seconds for snap in scene.snapshots)
    points: list[float] = []
    for t in sorted(t for t in times if scene.start_seconds <= t <= fade_start):
        # Sums of storyboard times can differ by an ulp (10.1 + 1.2 is not 11.3); one breakpoint, not two.
        if not points or t - points[-1] > 1e-9:
            points.append(t)
    active: list[tuple[str, float]] = []
    for index, at in enumerate(points):
        if at > scene.start_seconds:
            lines.append(f"{ind}self.wait_until({at:g})")
        for snap in scene.snapshots:
            if abs(snap.at_seconds - at) < 1e-9:
                lines.append(f'{ind}checkpoint(self, "{snap.id}", expected_time={at:g})')
        active = [(name, until) for name, until in active if until > at + 1e-9]
        for begins, until, kind, item in tracks:
            if abs(begins - at) > 1e-9:
                continue
            if kind == "reveal":
                name = f"reveal_{item.id}"  # type: ignore[attr-defined]
                lines.append(f"{ind}{name} = self.begin_reveal({item.id})")  # type: ignore[attr-defined]
            else:
                name = item.id  # type: ignore[attr-defined]
                lines.append(action_call(item, 8))  # type: ignore[arg-type]
            active.append((name, until))
        if index + 1 < len(points):
            nxt = points[index + 1]
            names = [name for name, until in active if until >= nxt - 1e-9]
            if names:
                lines.append(f"{ind}self.run_until({nxt:g}, [{', '.join(names)}])")
    carry = f", carry=[{', '.join(carried)}]" if carried else ""
    lines.append(f"{ind}self.end_scene(end_seconds={scene.end_seconds:g}, keep={is_last}{carry})")
    lines.append("")
    return lines


def generate_scene_module(spec: AnimationSpec, storyboard: Storyboard, style: ResolvedStyle) -> str:
    class_name = scene_class_name(spec.id)
    text = HEADER.format(project_id=spec.id, class_name=class_name, revision=storyboard.based_on_animation_revision)
    body: list[str] = []
    for index, scene in enumerate(storyboard.scenes):
        body.extend(scene_block(scene, style.tokens.motion, is_last=index == len(storyboard.scenes) - 1))
    body.append(f"        self.finish(total_seconds={spec.output.duration_seconds:g})")
    return text + "\n".join(body) + "\n"


def write_scene_module(spec: AnimationSpec, storyboard: Storyboard, style: ResolvedStyle, target: Path) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    text = generate_scene_module(spec, storyboard, style)
    compile(text, str(target), "exec")  # syntax check before writing
    target.write_text(text, encoding="utf-8")
    return target
